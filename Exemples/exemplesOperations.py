# Exemples d'opérations de base (selon les types de données) 
# 
# int 
a = 15
b = 2

print ('a',a, 'b', b)
print ('* :', a * b)
print ('/ :', a / b)
print ('// :', a // b)
print ('** :', a ** 2)  

# float 
a = 3.0
b = 2.0

print ('a',a, 'b', b)
print ('* :', a * b)
print ('/ :', a / b)
print ('** 2 :', a ** 2)  

#string 
a = 'aaa'
b = 'bbb'
print ('a',a, 'b', b)
print ('+ :', a + b)
print ('* 2 :', a * 2)

